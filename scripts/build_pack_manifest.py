"""Build the manifest of wissi-viz's 32-image public sample pack (run in CI: the data hosts aren't reachable from
every machine, and the manifest pins exact files, sizes and checksums so every download is the same).

    python scripts/build_pack_manifest.py src/wissi_viz/data/pack32.json

Sources (each verified to allow reuse, including commercial use):

* OpenSlide test data, Aperio CMU-1/2/3 — H&E, CC0 1.0.
* CAMELYON16 (AWS Open Data, s3://camelyon-dataset) — lymph-node H&E with expert tumour outlines, CC0 1.0.
* TCGA diagnostic slides (NCI Genomic Data Commons, open access) — one H&E slide per cancer type; open-access GDC
  data carry no use restrictions (acknowledge the TCGA Research Network).
* 10x Genomics Xenium example data — multiplex immunofluorescence morphology images with cell boundaries,
  CC BY 4.0 (attribute 10x Genomics).
"""
from __future__ import annotations

import json
import sys
import urllib.error
import urllib.parse
import urllib.request
import xml.etree.ElementTree as ET
from pathlib import Path

GDC = 'https://api.gdc.cancer.gov'
TCGA = ['TCGA-BRCA', 'TCGA-LUAD', 'TCGA-LUSC', 'TCGA-COAD', 'TCGA-PRAD', 'TCGA-SKCM', 'TCGA-KIRC', 'TCGA-LIHC',
        'TCGA-STAD', 'TCGA-BLCA', 'TCGA-HNSC', 'TCGA-THCA', 'TCGA-UCEC', 'TCGA-GBM', 'TCGA-OV', 'TCGA-PAAD',
        'TCGA-READ', 'TCGA-KIRP']
CAMELYON = 'https://camelyon-dataset.s3.amazonaws.com'
OPENSLIDE = 'https://openslide.cs.cmu.edu/download/openslide-testdata/Aperio'
XENIUM = [
    ('xenium-breast', 'Human breast cancer (Xenium, 2 FOVs)', '2.0.0/Xenium_V1_human_Breast_2fov/Xenium_V1_human_Breast_2fov_outs.zip'),
    ('xenium-lung', 'Human lung (Xenium, 2 FOVs)', '2.0.0/Xenium_V1_human_Lung_2fov/Xenium_V1_human_Lung_2fov_outs.zip'),
    ('xenium-kidney-protein', 'Human kidney, RNA + protein (Xenium)', '4.0.0/Xenium_V1_Protein_Human_Kidney_tiny/Xenium_V1_Protein_Human_Kidney_tiny_outs.zip'),
    ('xenium-ovary', 'Human ovary, immuno-oncology panel (Xenium)', '4.0.0/Xenium_V1_Human_Ovary_tiny/Xenium_V1_Human_Ovary_tiny_outs.zip'),
    ('xenium-ovary-multimodal', 'Human ovary, multimodal segmentation (Xenium)', '4.0.0/Xenium_V1_MultiCellSeg_Human_Ovary_tiny/Xenium_V1_MultiCellSeg_Human_Ovary_tiny_outs.zip'),
    ('xenium-mouse-ileum', 'Mouse ileum, Prime 5K (Xenium)', '3.0.0/Xenium_Prime_MultiCellSeg_Mouse_Ileum_tiny/Xenium_Prime_MultiCellSeg_Mouse_Ileum_tiny_outs.zip'),
]
LIC = {
    'cc0': {'licence': 'CC0-1.0', 'commercial_use': True},
    'gdc': {'licence': 'NCI GDC open access (no use restrictions)', 'commercial_use': True,
            'attribution': 'The results shown here are in part based upon data generated by the TCGA Research Network: https://www.cancer.gov/tcga'},
    'ccby': {'licence': 'CC-BY-4.0', 'commercial_use': True, 'attribution': 'Data: 10x Genomics, licensed under CC BY 4.0'},
}


def get(url: str, data: bytes | None = None, headers: dict | None = None):
    req = urllib.request.Request(url, data=data, headers={**UA, **(headers or {})}, method='POST' if data else 'GET')
    with urllib.request.urlopen(req, timeout=120) as r:
        return r.read()


UA = {'User-Agent': 'Mozilla/5.0 (wissi-viz sample-pack manifest builder)'}


def head_size(url: str) -> int:
    """Size in bytes: HEAD, else a one-byte ranged GET (some CDNs refuse HEAD)."""
    try:
        with urllib.request.urlopen(urllib.request.Request(url, method='HEAD', headers=UA), timeout=120) as r:
            n = int(r.headers.get('Content-Length') or 0)
            if n:
                return n
    except urllib.error.HTTPError:
        pass
    with urllib.request.urlopen(urllib.request.Request(url, headers={**UA, 'Range': 'bytes=0-0'}), timeout=120) as r:
        cr = r.headers.get('Content-Range') or ''
        return int(cr.rsplit('/', 1)[-1]) if '/' in cr else int(r.headers.get('Content-Length') or 0)


def tcga() -> list[dict]:
    out = []
    for proj in TCGA:
        filters = {'op': 'and', 'content': [
            {'op': 'in', 'content': {'field': 'cases.project.project_id', 'value': [proj]}},
            {'op': 'in', 'content': {'field': 'data_format', 'value': ['SVS']}},
            {'op': 'in', 'content': {'field': 'experimental_strategy', 'value': ['Diagnostic Slide']}},
            {'op': 'in', 'content': {'field': 'access', 'value': ['open']}},
            {'op': '>=', 'content': {'field': 'file_size', 'value': 120_000_000}},
            {'op': '<=', 'content': {'field': 'file_size', 'value': 700_000_000}}]}
        q = urllib.parse.urlencode({'filters': json.dumps(filters), 'size': 5, 'sort': 'file_size:asc', 'format': 'JSON',
                                    'fields': 'file_id,file_name,file_size,md5sum,cases.submitter_id,cases.primary_site'})
        hits = json.loads(get(f'{GDC}/files?{q}'))['data']['hits']
        if not hits:
            print(f'{proj}: no slide', file=sys.stderr)
            continue
        h = hits[0]
        case = (h.get('cases') or [{}])[0]
        out.append({'id': proj.lower(), 'title': f'{proj} ({case.get("primary_site", "")}), {case.get("submitter_id", "")}',
                    'kind': 'he', 'url': f'{GDC}/data/{h["file_id"]}', 'file': h['file_name'], 'size': h['file_size'],
                    'md5': h['md5sum'], 'source': 'TCGA via NCI Genomic Data Commons', **LIC['gdc']})
    return out


def camelyon(n: int = 5) -> list[dict]:
    def listing(prefix):
        items, token = [], None
        while True:
            q = {'list-type': '2', 'prefix': prefix}
            if token:
                q['continuation-token'] = token
            root = ET.fromstring(get(f'{CAMELYON}/?{urllib.parse.urlencode(q)}'))
            ns = {'s': root.tag.split('}')[0].strip('{')}
            for c in root.findall('s:Contents', ns):
                items.append((c.find('s:Key', ns).text, int(c.find('s:Size', ns).text), c.find('s:ETag', ns).text.strip('"')))
            if (root.findtext('s:IsTruncated', namespaces=ns) or 'false') == 'true':
                token = root.findtext('s:NextContinuationToken', namespaces=ns)
            else:
                return items
    imgs = {Path(k).stem: (k, s, e) for k, s, e in listing('CAMELYON16/images/') if k.endswith('.tif')}
    anns = {Path(k).stem: k for k, _, _ in listing('CAMELYON16/annotations/') if k.endswith('.xml')}
    tumours = sorted((s, stem) for stem, (k, s, e) in imgs.items() if stem in anns and 250e6 <= s <= 900e6)
    out = []
    for s, stem in tumours[:n]:
        k, size, etag = imgs[stem]
        item = {'id': f'camelyon16-{stem.replace("_", "-")}', 'title': f'CAMELYON16 {stem} (lymph node metastasis)',
                'kind': 'he', 'url': f'{CAMELYON}/{k}', 'file': Path(k).name, 'size': size,
                'annotations_url': f'{CAMELYON}/{anns[stem]}', 'source': 'CAMELYON16, AWS Open Data', **LIC['cc0']}
        if '-' not in etag:                       # single-part upload: the ETag is the MD5
            item['md5'] = etag
        out.append(item)
    return out


def openslide() -> list[dict]:
    out = []
    for n in ('CMU-1', 'CMU-2', 'CMU-3'):
        url = f'{OPENSLIDE}/{n}.svs'
        out.append({'id': n.lower(), 'title': f'OpenSlide {n} (Aperio H&E)', 'kind': 'he', 'url': url, 'file': f'{n}.svs',
                    'size': head_size(url), 'source': 'OpenSlide test data', **LIC['cc0']})
    return out


def xenium() -> list[dict]:
    out = []
    for i, title, path in XENIUM:
        url = f'https://cf.10xgenomics.com/samples/xenium/{path}'
        out.append({'id': i, 'title': title, 'kind': 'if', 'url': url, 'file': Path(path).name, 'size': head_size(url),
                    'unpack': 'xenium', 'source': '10x Genomics Xenium example data', **LIC['ccby']})
    return out


def main() -> None:
    out = Path(sys.argv[1] if len(sys.argv) > 1 else 'pack32.json')
    items, errors = [], []
    # 3 OpenSlide + 5 CAMELYON16 + 18 TCGA + 6 Xenium = 32
    for f in (openslide, camelyon, tcga, xenium):
        try:
            items += f()
        except Exception as e:  # noqa: BLE001  (report every source, then fail)
            errors.append(f'{f.__name__}: {type(e).__name__}: {e}')
    if errors:
        print('ERRORS: ' + ' | '.join(errors))
        if len(items) < 20:
            raise SystemExit(1)
    quick = ['cmu-1', 'cmu-2', 'cmu-3', 'xenium-breast', 'xenium-kidney-protein']
    doc = {'name': 'wissi-viz public sample pack', 'version': 1, 'items': items, 'quick': quick,
           'total_bytes': sum(x['size'] for x in items),
           'note': 'Every image allows reuse including commercial use; see each item\'s licence and attribution.'}
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(doc, indent=1))
    print(f'{len(items)} images, {doc["total_bytes"] / 1e9:.1f} GB → {out}')
    for x in items:
        print(f'  {x["id"]:28s} {x["size"] / 1e6:8.0f} MB  {x["licence"]}')


if __name__ == '__main__':
    main()
